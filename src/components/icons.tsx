/** 파일 형식 배지 (W = 워드, X = 엑셀) */
export function FileBadge({ kind, className = "" }: { kind: "word" | "excel"; className?: string }) {
  const color = kind === "word" ? "bg-blue-600" : "bg-emerald-600";
  return (
    <span
      className={`inline-flex shrink-0 items-center justify-center rounded-lg font-bold text-white ${color} ${className}`}
      aria-hidden="true"
    >
      {kind === "word" ? "W" : "X"}
    </span>
  );
}
